const email=process.env.MONITOR_TEST_EMAIL || 'preview@monitor.local'
const password=process.env.MONITOR_TEST_PASSWORD || 'local-preview-password-2026'
async function login(page:Page) {
 await page.goto('/chenv-admin')
 await page.getByLabel('邮箱',{exact:true}).fill(email)
 await page.getByLabel('密码',{exact:true}).fill(password)
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await expect(page.getByRole('heading',{name:'管理后台',exact:true})).toBeVisible()
}
async function token(request:APIRequestContext) {
 const r=await request.post('/api/collections/_superusers/auth-with-password',{data:{identity:email,password}})
 expect(r.ok()).toBeTruthy();return (await r.json()).token as string
}
